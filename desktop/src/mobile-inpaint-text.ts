const languages = ['zh-TW', 'en-US', 'ja-JP', 'ko-KR'];
export function mobileInpaintText(language: string | undefined, key: string, params: Record<string, string | number> = {}): string {
  if (key.startsWith('Error: ')) return 'Error: ' + mobileInpaintText(language, key.slice(7), params);
  const index = languages.indexOf(language ?? '');
  let row = messages[key], values = params;
  if (!row) {
    const layer = /^重绘 (\d+)$/.exec(key);
    if (layer) { row = messages['重绘 {number}']; values = { number: layer[1] }; key = '重绘 {number}'; }
  }
  const text = row ? (index < 0 ? key : row[index]) : featureText(language, key, values);
  return text.replace(/\{(\w+)\}/g, (token, name: string) => values[name] === undefined ? token : String(values[name]));
}
