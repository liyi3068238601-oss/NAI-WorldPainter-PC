function replaceSection(markdown: string, startHeading: string, endHeading: string, replacement: string): string {
  const start = markdown.indexOf(startHeading);
  const end = start < 0 ? -1 : markdown.indexOf(endHeading, start + startHeading.length);
  if (start < 0 || end < 0) throw Error(`提示词参考结构变化，无法适配章节：${startHeading}`);
  return `${markdown.slice(0, start)}${replacement.trim()}\n\n${markdown.slice(end)}`;
}

function replaceOnce(markdown: string, before: string, after: string, label: string): string {
  const first = markdown.indexOf(before);
  if (first < 0 || markdown.indexOf(before, first + before.length) >= 0) {
    throw Error(`提示词参考结构变化，无法适配段落：${label}`);
  }
  return `${markdown.slice(0, first)}${after}${markdown.slice(first + before.length)}`;
}

