export function adaptPromptingReference(name: PromptingReferenceName, source: string): string {
  const normalized = source.replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
  const body = name === 'ideation' ? adaptIdeation(normalized) : adaptWriting(normalized);
  if (/\blangbai_[a-z0-9_]+\b/i.test(body) || /\bsearch_tags\b/i.test(body) || /工具调用只有\s*4\s*步/.test(body) ||
      /角色栏只写外貌|只放外貌|动作\s*[·,、/]+\s*表情\s*[·,、/]+\s*镜头.{0,16}一律不进角色栏|角色栏只有性别词\+角色名/.test(body)) {
    throw Error('提示词参考包含未适配的移动端工具流程。');
  }
  return `> PC 端适配版；创作方法保留为参考，应用操作与权限以当前 PC 实际能力和对话要求为准。\n> 本资料仅能通过 read_prompting_reference 的 ideation 或 writing 项按需读取。\n\n${body}`;
}
