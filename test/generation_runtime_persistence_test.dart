    await environment.openStores();
    final stored = await environment.workspace!.load();
    expect(stored, isNotNull);
    final workspaceJson = jsonEncode(stored!.data);
    expect(workspaceJson, isNot(contains(base64Encode(firstOutput))));
    expect(workspaceJson, isNot(contains(base64Encode(secondOutput))));

    final reopened = WorkbenchController(
      store: environment.workspace,
      restored: stored,
      assets: environment.assets,
    );
    environment.controller = reopened;
    final restoredResult = reopened.results.singleWhere(
      (result) => result.id == generated.id,
    );
    expect(restoredResult.favorite, isTrue);
    expect(restoredResult.seed, 0);
    expect(restoredResult.assetRef, expectedAssetRef);
    expect(
      restoredResult.parameters!.toJson(),
      equals(generatedParameters.toJson()),
    );

    final restoredBytes = await environment.assets!.read(
      restoredResult.assetRef!,
    );
    expect(_bytesEqual(restoredBytes, firstOutput), isTrue);
    expect(sha256.convert(restoredBytes).toString(), expectedDigest);
    final restoredReference = await environment.assets!.read(
      referenceAsset.assetRef,
    );
    expect(_bytesEqual(restoredReference, referenceBytes), isTrue);
    await reopened.flush();
  });

  test('keeps sanitized service failures out of the gallery', () async {
    final environment = await _TestEnvironment.create();
    addTearDown(environment.dispose);
    await environment.openStores();

    final vault = SessionMemoryCredentialVault();
    final connection = ServiceConnection(
      protocol: 'ikun',
      baseUrl: 'https://mock.example',
    );
    await connection.saveSecret(vault, 'synthetic-error-token');
    var requestCount = 0;
    final runtime = GenerationRuntime(
      assets: environment.assets!,
      vault: vault,
      clientFactory: () => MockClient((request) async {
        requestCount++;
        return http.Response('synthetic-private-response', 429);
      }),
    );
    final controller = WorkbenchController(
      store: environment.workspace,
      generateImage: runtime.generate,
      cancelRequest: runtime.cancel,
      assets: environment.assets,
      vault: vault,
    );
    environment.controller = controller;
    controller
      ..updateProvider('ikun 网关')
      ..updateConnection(connection)
      ..updatePrompt('safe mocked failure')
      ..updateModel('NAI Diffusion 5 Curated')
      ..updateSeed('0');

    await controller.generate();
    await controller.flush();

    expect(requestCount, 1);
    expect(controller.status, '请求过于频繁，请稍后重试');
    expect(controller.status, isNot(contains('synthetic-private-response')));
    expect(controller.status, isNot(contains('synthetic-error-token')));
    expect(controller.results.where((result) => !result.isDemo), isEmpty);
    final stored = await environment.workspace!.load();
    expect(stored, isNotNull);
    expect((stored!.data['gallery'] as List), hasLength(3));
  });
