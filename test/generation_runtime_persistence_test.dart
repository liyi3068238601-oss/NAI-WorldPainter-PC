  test('persists generated bytes and frozen advanced gallery parameters across reopen', () async {
    final environment = await _TestEnvironment.create();
    addTearDown(environment.dispose);
    await environment.openStores();

    final referenceBytes = _createTwoByTwoPng(0x22, 0x86, 0xd1);
    final firstOutput = _createTwoByTwoPng(0xe7, 0x56, 0x39);
    final secondOutput = _createTwoByTwoPng(0x39, 0xb5, 0x72);
    final referenceAsset = await environment.assets!.save(referenceBytes);
    final vault = SessionMemoryCredentialVault();
    final connection = ServiceConnection(
      protocol: 'ikun',
      baseUrl: 'https://mock.example',
    );
    await connection.saveSecret(vault, 'synthetic-test-token');

    final firstResponseGate = Completer<void>();
    environment.responseGate = firstResponseGate;
    final firstRequestReceived = Completer<void>();
    final requests = <http.Request>[];
    final runtime = GenerationRuntime(
      assets: environment.assets!,
      vault: vault,
      clientFactory: () => MockClient((request) async {
        final requestIndex = requests.length;
        requests.add(request);
        if (requestIndex == 0) {
          firstRequestReceived.complete();
          await firstResponseGate.future;
        }
        final output = requestIndex == 0 ? firstOutput : secondOutput;
        return http.Response(
          jsonEncode({
            'data': [
              {'b64_json': base64Encode(output)},
            ],
          }),
          200,
          headers: const {'content-type': 'application/json'},
        );
      }),
    );

    final controller = WorkbenchController(
      store: environment.workspace,
      generateImage: runtime.generate,
      cancelRequest: runtime.cancel,
      assets: environment.assets,
      vault: vault,
    );
    environment.controller = controller;

    const prompt = 'silver-haired traveler beneath a blue lantern';
    const negative = 'blurry, signature, watermark';
    final frozenParameters = GenerationParameters(
      operation: GenerationOperation.textToImage,
      model: 'nai-diffusion-5-curated',
      prompt: prompt,
      negativePrompt: negative,
      width: 768,
      height: 1024,
      steps: 26,
      scale: 5.35,
      cfgRescale: 0.15,
      sampler: 'k_dpmpp_2m',
      noiseSchedule: 'exponential',
      seed: 0,
      useCoords: false,
      characters: [
        GenerationCharacter(
          prompt: 'silver hair',
          negativePrompt: 'brown hair',
          centerX: 0.4,
          centerY: 0.6,
        ),
      ],
      preciseReferences: [
        PreciseReference(
          assetId: referenceAsset.assetRef,
          referenceType: 'character',
          strength: 0.83,
        ),
      ],
    );
    controller
      ..updateProvider('ikun 网关')
      ..updateConnection(connection)
      ..updateAdvanced(frozenParameters)
      ..updateModel('NAI Diffusion 5 Curated')
      ..updatePrompt(prompt)
      ..updateNegative(negative)
      ..setSize(768, 1024)
      ..updateSteps(26)
      ..updateCfg(5.35)
      ..updateSeed('0')
      ..updateBatch(2);
    await controller.flush();

    environment.generation = controller.generate();
    await firstRequestReceived.future;
    final firstRequest = requests.first;
    final firstPayload = jsonDecode(firstRequest.body) as Map<String, dynamic>;
    expect(firstRequest.url.path, '/v1/images/generations');
    expect(
      firstRequest.headers['authorization'],
      'Bearer synthetic-test-token',
    );
    expect(firstRequest.body, isNot(contains('synthetic-test-token')));
    expect(firstPayload['novelai_operation'], 'precise-reference');
    expect(firstPayload['prompt'], prompt);
    expect(firstPayload['negative_prompt'], negative);
    expect(firstPayload['model'], 'nai-diffusion-5-curated');
    expect(firstPayload['width'], 768);
    expect(firstPayload['height'], 1024);
    expect(firstPayload['steps'], 26);
    expect(firstPayload['scale'], 5.35);
    expect(firstPayload['cfg_rescale'], 0.15);
    expect(firstPayload['sampler'], 'k_dpmpp_2m');
    expect(firstPayload['noise_schedule'], 'exponential');
    expect(firstPayload['seed'], 0);
    final sentReference =
        (firstPayload['references'] as List).single as Map<String, dynamic>;
    expect(sentReference['reference_image'], base64Encode(referenceBytes));
    expect(sentReference['reference_type'], 'character');
    expect(sentReference['strength'], 0.83);

    // Edits made after submission belong to the next request only.
    controller
      ..updatePrompt('edited while the first request is in flight')
      ..updateSteps(41)
      ..updateCfg(7.2)
      ..updateAdvanced(
        controller.parameters.copyWith(
          cfgRescale: 0.4,
          preciseReferences: [
            PreciseReference(
              assetId: referenceAsset.assetRef,
              referenceType: 'character',
              strength: 0.2,
            ),
          ],
        ),
      );
    await controller.flush();
    firstResponseGate.complete();
    await environment.generation;

    expect(requests, hasLength(2));
    final secondPayload = jsonDecode(requests[1].body) as Map<String, dynamic>;
    expect(secondPayload['prompt'], prompt);
    expect(secondPayload['steps'], 26);
    expect(secondPayload['seed'], isA<int>());
    expect(controller.prompt, 'edited while the first request is in flight');

    final expectedDigest = sha256.convert(firstOutput).toString();
    final expectedAssetRef =
        'sha256/${expectedDigest.substring(0, 2)}/$expectedDigest.png';
    final generated = controller.results.singleWhere(
      (result) => result.assetRef == expectedAssetRef,
    );
    expect(generated.isDemo, isFalse);
    expect(generated.seed, 0);
    expect(generated.favorite, isFalse);
    expect(generated.prompt, prompt);
    expect(generated.negative, negative);
    expect(generated.width, 2);
    expect(generated.height, 2);
    expect(generated.steps, 26);
    expect(generated.cfg, 5.35);
    expect(generated.assetRef, expectedAssetRef);

    final generatedParameters = generated.parameters!;
    expect(generatedParameters.prompt, prompt);
    expect(generatedParameters.negativePrompt, negative);
    expect(generatedParameters.model, 'nai-diffusion-5-curated');
