class _TestEnvironment {
  _TestEnvironment(this.root, this.directory);

  final Directory root;
  final Directory directory;
  SQLiteWorkspaceStore? workspace;
  ImageAssetStore? assets;
  WorkbenchController? controller;
  Completer<void>? responseGate;
  Future<void>? generation;

  static Future<_TestEnvironment> create() async {
    final root = Directory(
      p.join(Directory.current.path, '.tmp', 'generation-runtime-tests'),
    );
    await root.create(recursive: true);
    final directory = await root.createTemp('runtime-persistence-');
    return _TestEnvironment(root, directory);
  }

  Future<void> openStores() async {
    workspace = await SQLiteWorkspaceStore.open(
      factory: databaseFactoryFfi,
      path: p.join(directory.path, 'workspace.sqlite'),
    );
    assets = await openImageAssetStore(directory: directory.path);
  }

  Future<void> closeOpenResources() async {
    final activeController = controller;
    if (activeController != null) {
      if (activeController.generating) activeController.cancelGeneration();
      final gate = responseGate;
      if (gate != null && !gate.isCompleted) gate.complete();
      final activeGeneration = generation;
      if (activeGeneration != null) await activeGeneration;
      if (!activeController.closing) {
        await activeController.closeStorage();
      }
      activeController.dispose();
      controller = null;
      workspace = null;
      assets = null;
      generation = null;
      responseGate = null;
      return;
    }

    await workspace?.close();
    await assets?.close();
    workspace = null;
    assets = null;
  }

  Future<void> dispose() async {
    await closeOpenResources();
    await _deleteTemporaryDirectorySafely(root, directory);
  }
}

Future<void> _deleteTemporaryDirectorySafely(
  Directory root,
  Directory target,
) async {
  if (!await target.exists()) return;

  final canonicalRoot = p.normalize(await root.resolveSymbolicLinks());
  final canonicalTarget = p.normalize(await target.resolveSymbolicLinks());
  if (p.equals(canonicalRoot, canonicalTarget) ||
      !p.isWithin(canonicalRoot, canonicalTarget)) {
    throw StateError('Refusing to remove a path outside the test temp root.');
  }
  await Directory(canonicalTarget).delete(recursive: true);
}

Uint8List _createTwoByTwoPng(int red, int green, int blue) {
  const pngSignature = <int>[137, 80, 78, 71, 13, 10, 26, 10];
  final rawPixels = <int>[
    0,
    red,
    green,
    blue,
    0xff,
    red,
    green,
    blue,
    0xff,
    0,
    red,
    green,
    blue,
    0xff,
    red,
    green,
    blue,
    0xff,
  ];
  final header = ByteData(13)
    ..setUint32(0, 2, Endian.big)
    ..setUint32(4, 2, Endian.big)
    ..setUint8(8, 8)
    ..setUint8(9, 6)
    ..setUint8(10, 0)
    ..setUint8(11, 0)
    ..setUint8(12, 0);
  final output = BytesBuilder(copy: false)..add(pngSignature);
  _addPngChunk(output, 'IHDR', header.buffer.asUint8List());
  _addPngChunk(output, 'IDAT', ZLibEncoder().convert(rawPixels));
  _addPngChunk(output, 'IEND', const <int>[]);
  return output.takeBytes();
}

void _addPngChunk(BytesBuilder output, String type, List<int> data) {
  final typeBytes = ascii.encode(type);
  output.add(_uint32Bytes(data.length));
  output.add(typeBytes);
  output.add(data);
  output.add(_uint32Bytes(_crc32(<int>[...typeBytes, ...data])));
}

List<int> _uint32Bytes(int value) =>
    (ByteData(4)..setUint32(0, value, Endian.big)).buffer.asUint8List();

int _crc32(List<int> bytes) {
  var crc = 0xffffffff;
  for (final byte in bytes) {
    crc ^= byte;
    for (var bit = 0; bit < 8; bit++) {
      crc = (crc & 1) == 1 ? (crc >> 1) ^ 0xedb88320 : crc >> 1;
    }
  }
  return (crc ^ 0xffffffff) & 0xffffffff;
}

bool _bytesEqual(List<int> left, List<int> right) {
  if (left.length != right.length) return false;
  for (var index = 0; index < left.length; index++) {
    if (left[index] != right[index]) return false;
  }
  return true;
}
